#include <benchmark/benchmark.h>

#include <ufw/core/mem/memory_region.hpp>

#include <cstddef>
#include <exception>
#include <span>

namespace {

using ufw::core::lock;
using ufw::core::memory_region;
using ufw::core::prot;

// Region lifecycle: mmap + first-touch-free construct, then munmap.
void mem_create_destroy(benchmark::State& state)
{
    auto const bytes = static_cast<std::size_t>(state.range(0));
    for (auto _ : state)
    {
        memory_region r{{.bytes = bytes}};
        benchmark::DoNotOptimize(r.data());
    }
    state.SetBytesProcessed(state.iterations() * static_cast<std::int64_t>(bytes));
}
BENCHMARK(mem_create_destroy)->RangeMultiplier(8)->Range(4096, 16 << 20);

// Same, plus PROT_NONE guard pages bracketing the region (two extra mprotect calls).
void mem_create_destroy_guarded(benchmark::State& state)
{
    auto const bytes = static_cast<std::size_t>(state.range(0));
    for (auto _ : state)
    {
        memory_region r{{.bytes = bytes, .guard_pages = true}};
        benchmark::DoNotOptimize(r.data());
    }
}
BENCHMARK(mem_create_destroy_guarded)->RangeMultiplier(8)->Range(4096, 1 << 20);

// Same, plus mlock (pages pinned resident). Capped small to stay under
// RLIMIT_MEMLOCK; skips gracefully if locking is denied by the environment.
void mem_create_destroy_locked(benchmark::State& state)
{
    auto const bytes = static_cast<std::size_t>(state.range(0));
    try
    {
        for (auto _ : state)
        {
            memory_region r{{.bytes = bytes, .locking = lock::resident}};
            benchmark::DoNotOptimize(r.data());
        }
    }
    catch (std::exception const& e)
    {
        state.SkipWithError(e.what());
    }
}
BENCHMARK(mem_create_destroy_locked)->RangeMultiplier(8)->Range(4096, 64 << 10);

// Cost of a single mprotect on an already-mapped 64 KiB region (toggling RO/RW).
void mem_protect(benchmark::State& state)
{
    memory_region r{{.bytes = 64 << 10}};
    std::span<std::byte> const all{r.data(), r.size()};
    bool read_only = false;
    for (auto _ : state)
    {
        r.protect(all, read_only ? prot::read_write : prot::read_only);
        read_only = !read_only;
        benchmark::ClobberMemory();
    }
}
BENCHMARK(mem_protect);

} // namespace

