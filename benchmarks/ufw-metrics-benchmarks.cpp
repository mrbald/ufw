#include <benchmark/benchmark.h>

#include <ufw/core/metrics/metrics.hpp>
#include <ufw/core/sys/affinity.hpp>
#include <ufw/core/sys/timing.hpp>

#include <cstdint>

namespace {

namespace mx = ufw::core::metrics;

void metrics_counter_add(benchmark::State& state)
{
    ufw::core::pin_thread(0);
    mx::registry reg{{}};
    auto const c = reg.make_counter("bench_counter_total");
    for (auto _ : state)
    {
        c.add();
    }
    state.SetItemsProcessed(state.iterations());
}
BENCHMARK(metrics_counter_add);

void metrics_value_f64_set(benchmark::State& state)
{
    ufw::core::pin_thread(0);
    mx::registry reg{{}};
    auto const v = reg.make_value_f64("bench_value");
    double x = 0.0;
    for (auto _ : state)
    {
        v.set(x += 0.5);
    }
    state.SetItemsProcessed(state.iterations());
}
BENCHMARK(metrics_value_f64_set);

// The G6-relevant number: the full series record (seqlock + Welford + EWMA +
// histogram bucket + worst-N scan) — what the column drainer pays per message
// when dispatch-latency telemetry is on.
void metrics_series_record(benchmark::State& state)
{
    ufw::core::pin_thread(0);
    mx::registry reg{{}};
    auto const s = reg.make_series("bench_series_ns");
    std::uint64_t sample = 1;
    for (auto _ : state)
    {
        s.record(sample, sample);
        sample = (sample * 25) % 100'000; // spread across buckets like real latencies
    }
    state.SetItemsProcessed(state.iterations());
}
BENCHMARK(metrics_series_record);

} // namespace

