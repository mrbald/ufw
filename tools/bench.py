#!/usr/bin/env python3
"""
Run a domain's google-benchmark suite and record the result table in a delimited
block at the bottom of its source file, so the performance numbers travel with
the code in git — a commit that changes the code and re-runs this shows the
number delta right next to the code delta.

Usage:
    # build the optimized binary first (numbers from a Debug/asan build are noise):
    cmake --preset conan-release -DUFW_ENABLE_CLANG_TIDY=OFF
    cmake --build --preset conan-release --target ufw_benchmarks -j
    # then record:
    python3 tools/bench.py mem        # updates benchmarks/ufw-mem-benchmarks.cpp

No third-party deps.
"""
from __future__ import annotations

import argparse
import platform
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent

BEGIN = "// <<<BENCHMARK RESULTS — regenerated by tools/bench.py; do not edit below>>>"
END = "// <<<END BENCHMARK RESULTS>>>"

# domain -> (benchmark name filter, source file to annotate)
DOMAINS = {
    "mem":  ("mem_",  "benchmarks/ufw-mem-benchmarks.cpp"),
    "ring": ("ring_", "benchmarks/ufw-ring-benchmarks.cpp"),
}


def main() -> int:
    p = argparse.ArgumentParser(description="record benchmark results into the source file")
    p.add_argument("domain", choices=sorted(DOMAINS))
    p.add_argument("--build-dir", default="build/Release",
                   help="optimized build dir holding benchmarks/ufw_benchmarks (default build/Release)")
    p.add_argument("--min-time", default="0.2s")
    args = p.parse_args()

    filt, src_rel = DOMAINS[args.domain]
    src = ROOT / src_rel
    bench = ROOT / args.build_dir / "benchmarks" / "ufw_benchmarks"
    if not bench.exists():
        sys.exit(f"error: {bench} not found — build the optimized ufw_benchmarks target first")
    if not src.is_file():
        sys.exit(f"error: {src} not found")

    proc = subprocess.run(
        [str(bench), f"--benchmark_filter={filt}", f"--benchmark_min_time={args.min_time}"],
        capture_output=True, text=True)
    if proc.returncode != 0:
        sys.stderr.write(proc.stdout + proc.stderr)
        sys.exit(f"benchmark run failed (exit {proc.returncode})")

    # Keep the result table (from the "Benchmark" header row onward), dropping the
    # noisy clock/affinity preamble that varies run-to-run.
    out_lines = proc.stdout.splitlines()
    start = next((i for i, ln in enumerate(out_lines) if ln.startswith("Benchmark")), 0)
    table = [ln for ln in out_lines[start:] if ln.strip()]
    if not table:
        sys.exit("no benchmark output captured")

    header = f"// platform: {platform.system()} {platform.machine()} | build: {args.build_dir} | filter: {filt}"
    body = "\n".join(f"// {ln}" for ln in table)
    block = f"{BEGIN}\n{header}\n{body}\n{END}\n"

    text = src.read_text()
    pattern = re.compile(re.escape(BEGIN) + r".*?" + re.escape(END) + r"\n?", re.S)
    text = pattern.sub(block, text) if pattern.search(text) else text.rstrip() + "\n\n" + block
    src.write_text(text)
    print(f"recorded {len(table)} lines into {src_rel}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
